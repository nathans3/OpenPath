// Records every built-in OpenPath sentence once with ElevenLabs and ships it
// with the app, so guide steps and scam warnings cost nothing to speak for
// every user. Run once per release (about 25,000 characters ≈ $1.25):
//
//   ELEVENLABS_API_KEY=... npm run voice-pack
//
// Optional: ELEVENLABS_VOICE_ID (defaults to the app's voice). Writes mp3
// files and manifest.js into app/voice/. Already-recorded sentences are kept.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appJs = path.join(here, "..", "app", "js");
const outDir = path.join(here, "..", "app", "voice");
const { allGuideSentences } = await import(path.join(appJs, "knowledge.js"));
const { allRefusalSentences } = await import(path.join(appJs, "guardrails.js"));
const { STRINGS_FOR_VOICE } = await import(path.join(appJs, "i18n.js"));

const key = (process.env.ELEVENLABS_API_KEY || "").trim();
if (!key) { console.error("Set ELEVENLABS_API_KEY first."); process.exit(1); }
const voiceId = process.env.ELEVENLABS_VOICE_ID || "EXAVITQu4vr4xnSDxMaL";
const style = "warm";

const guides = allGuideSentences(), refusals = allRefusalSentences();
const manifestFile = path.join(outDir, "manifest.js");
let manifest = {};
try { manifest = (await import(manifestFile + "?t=" + Date.now())).default || {}; } catch { /* first run */ }

let billed = 0, made = 0;
for (const lang of Object.keys(guides)) {
  const sentences = [...new Set([...guides[lang], ...refusals[lang], ...STRINGS_FOR_VOICE(lang)])];
  for (const text of sentences) {
    const id = crypto.createHash("sha256").update(`${lang}|${style}|${text}`).digest("hex");
    const file = `${id.slice(0, 24)}.mp3`;
    if (manifest[id] && fs.existsSync(path.join(outDir, manifest[id]))) continue;
    const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voiceId}?output_format=mp3_22050_32`, {
      method: "POST",
      headers: { "xi-api-key": key, "Content-Type": "application/json" },
      body: JSON.stringify({ text, model_id: "eleven_flash_v2_5", voice_settings: { stability: 0.42, similarity_boost: 0.8, style: 0.45, use_speaker_boost: true } }),
    });
    if (!res.ok) { console.error(`ElevenLabs ${res.status} on: ${text.slice(0, 60)}`); process.exit(1); }
    fs.writeFileSync(path.join(outDir, file), Buffer.from(await res.arrayBuffer()));
    manifest[id] = file; billed += text.length; made++;
    process.stdout.write(`\r${made} clips recorded`);
  }
}
fs.writeFileSync(manifestFile, "// Generated by scripts/build-voice-pack.mjs. Do not edit by hand.\nexport default " + JSON.stringify(manifest, null, 0) + ";\n");
console.log(`\nDone: ${made} new clips, ${billed.toLocaleString()} characters billed (≈ $${(billed / 1000 * 0.05).toFixed(2)}), ${Object.keys(manifest).length} clips in the pack.`);
